// Writes roots/<cut>.html for every cut (cup, cup4, falkor, full, nebius) from its clock: one sub-composition slot per scene, back to back, the
// caption track over the whole cut and the mixed soundtrack. A root's length is fixed in its HTML, so it is generated
// from the clock rather than typed. Usage: node tools/make-roots.mjs
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { CUTS, SCRIPTS, loadClock } from "../assets/js/clocks.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const FILE = {
  coldOpen: "01-cold-open", meet: "02-meet", brief: "03-brief", order: "04-order", kitchen: "05-kitchen", office: "06-office",
  negotiation: "07-negotiation", graph: "07b-graph", cares: "08-cares", dev: "09-dev", also: "09b-also", close: "10-close",
};
const TITLE = { cup: "Munim launch film · Cup cut (2:55)", cup4: "Munim launch film · Cup cut (4:00)", falkor: "Munim launch film · FalkorDB cut", full: "Munim launch film · full tour", nebius: "Munim · Nebius cut" };
// A cut with its own scene files names them in its clock (T.files); its extra styles and scripts load after the shared ones.
const EXTRA = {
  nebius: { css: ["styles/nebius.css"], js: ["assets/screens/nebius/shots.js", "assets/js/nebius.js"] },
};

for (const cut of CUTS) {
  const T = await loadClock(cut);
  const slots = T.order.map((k) => {
    const s = T.scenes[k];
    return `      <div id="${k}" data-composition-id="${k}" data-composition-src="scenes/${T.files?.[k] ?? FILE[k]}.html" data-start="${s.start}" data-duration="${s.dur}" data-track-index="1" data-track-kind="graphics" data-width="1920" data-height="1080"></div>`;
  });
  const html = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
    <title>${TITLE[cut]}</title>
    <!-- GENERATED by tools/make-roots.mjs from assets/js/timing-${cut}.js: change the clock, then run it again. -->
    <link rel="stylesheet" href="styles/fonts.css" />
    <link rel="stylesheet" href="styles/tokens.css" />
    <link rel="stylesheet" href="styles/video.css" />
    <link rel="stylesheet" href="styles/chrome.css" />
    <link rel="stylesheet" href="ui/cobnut.css" />
${(EXTRA[cut]?.css ?? []).map((f) => `    <link rel="stylesheet" href="${f}" />\n`).join("")}    <script src="vendor/gsap.min.js"></script>
    <script>window.CUT = "${cut}";</script>
    <script src="assets/js/fixture.js"></script>
${SCRIPTS[cut].map((f) => `    <script src="assets/js/${f}"></script>`).join("\n")}
    <script src="assets/js/motion.js"></script>
    <script src="assets/js/scene.js"></script>
    <script src="assets/js/beats.js"></script>
    <script src="ui/cobnut.js"></script>
    <script src="ui/shop.js"></script>
    <script src="ui/staff.js"></script>
    <script src="ui/more.js"></script>
    <script src="ui/site.js"></script>
    <script src="ui/negotiation.js"></script>
    <script src="ui/graph.js"></script>
${(EXTRA[cut]?.js ?? []).map((f) => `    <script src="${f}"></script>\n`).join("")}    <script>window.T = TIMING[CUT];</script>
    <style>
      #root {
        position: relative;
        width: 100%;
        height: 100%;
        overflow: hidden;
      }
      [data-composition-id="${cut}"] > div[data-composition-src] {
        position: absolute;
        inset: 0;
      }
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="${cut}" data-start="0" data-duration="${T.duration}" data-width="1920" data-height="1080">
${slots.join("\n")}
${T.overlays ? T.overlays.map((o) => `      <div id="${o.id}" data-composition-id="${o.id}" data-composition-src="scenes/${o.file}.html" data-start="0" data-duration="${T.duration}" data-track-index="${o.track}" data-track-kind="graphics" data-width="1920" data-height="1080"></div>\n`).join("") : ""}      <div id="captions" data-composition-id="captions" data-composition-src="scenes/captions.html" data-start="0" data-duration="${T.duration}" data-track-index="2" data-track-kind="captions" data-width="1920" data-height="1080"></div>
      <audio id="${cut}-mix" src="assets/audio/mix-${cut}.wav" data-start="0" data-duration="${T.duration}" data-track-index="10" data-volume="1"></audio>
    </div>
    <script>
      window.__timelines["${cut}"] = gsap.timeline({ paused: true });
    </script>
  </body>
</html>
`;
  writeFileSync(join(ROOT, "roots", `${cut}.html`), html);
  console.log(`roots/${cut}.html: ${T.order.length} scenes, ${T.duration} s`);
}
